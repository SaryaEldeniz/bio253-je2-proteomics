source(if(file.exists("Sarya_George.Rproj")) "R/setup.R" else "Sarya_George/R/setup.R")
checks<-character()
verify<-function(name,ok) {if(!isTRUE(ok))stop(name); checks<<-c(checks,name)}
universe<-paste0("g",1:100); foreground<-paste0("g",1:10)
sets<-list(enriched=paste0("g",1:20),zero=paste0("g",51:70),small="g1")
x<-run_step05_ora(foreground,universe,sets)
p<-fisher.test(matrix(c(10,0,10,80),nrow=2),alternative="greater")$p.value
verify("ORA matches one-sided Fisher exact test",abs(x$p_value[x$pathway=="enriched"]-p)<1e-12)
verify("Zero-overlap pathways remain with p=1",x$p_value[x$pathway=="zero"]==1)
verify("Effective size filtering excludes small terms",!"small" %in% x$pathway)
verify("Empty foreground is valid with p=1",all(run_step05_ora(character(),universe,sets)$p_value==1))
duplicate<-run_step05_ora(c(foreground,foreground),c(universe,universe),sets)
verify("Duplicate memberships and input IDs do not multiply counts",identical(x,duplicate))
bad<-tryCatch({run_step05_ora("not_in_universe",universe,sets);FALSE},error=function(e)TRUE)
verify("Mismatched foreground/background is rejected",bad)
f<-tibble(policy="primary",contrast=c("a","a","b"),p_value=c(.01,.5,NA_real_))
f<-step05_adjust(f,"p_value")
verify("Failed estimates remain NA with conservative family size",is.na(f$FDR_study[3])&&abs(f$FDR_study[1]-.03)<1e-12)
writeLines(c("# Step 5 ORA checks","",paste(length(checks),"checks passed."),"",paste0("- PASS: ",checks)),file.path(REPO_ROOT,"reports","step05_ora_checks.md"))
message(length(checks),"/",length(checks)," ORA checks passed.")
